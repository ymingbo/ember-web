export default {
  write(ctx, bus, addr, value) {
    if ((addr & 0x6100) !== 0x4100) return;
    ctx.window('prg-8000-32k').setBank((value >> 2) & 0x01);
    ctx.window('chr-0000').setBank(value & 0x03);
  }
};

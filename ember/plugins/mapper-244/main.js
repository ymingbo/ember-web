const PRG = [
  [0, 1, 2, 3],
  [3, 2, 1, 0],
  [0, 2, 1, 3],
  [3, 1, 2, 0]
];
const CHR = [
  [0, 1, 2, 3, 4, 5, 6, 7],
  [0, 2, 1, 3, 4, 6, 5, 7],
  [0, 1, 4, 5, 2, 3, 6, 7],
  [0, 4, 1, 5, 2, 6, 3, 7],
  [0, 4, 2, 6, 1, 5, 3, 7],
  [0, 2, 4, 6, 1, 3, 5, 7],
  [7, 6, 5, 4, 3, 2, 1, 0],
  [7, 6, 5, 4, 3, 2, 1, 0]
];

export default {
  write(ctx, bus, addr, value) {
    if ((value & 0x08) !== 0) ctx.window('chr-0000').setBank(CHR[(value >> 4) & 0x07][value & 0x07]);
    else ctx.window('prg-8000-32k').setBank(PRG[(value >> 4) & 0x03][value & 0x03]);
  }
};

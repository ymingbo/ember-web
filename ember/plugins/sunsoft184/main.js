export default {
  write(ctx, bus, addr, value) {
    ctx.window('chr-0000').setBank(value & 0x07);
    // 硬件上位 6-4 的最高位恒为 1，所以只能选 4-7。
    ctx.window('chr-1000').setBank(0x04 | ((value >> 4) & 0x03));
  }
};

PrinterText::PrinterText(contracts::hardware::ParallelPort& port) : port_(port) {}

void PrinterText::write(std::uint8_t value) {
  value &= 0x7F;
  if (value >= FIRST_PRINTABLE && value <= LAST_PRINTABLE) {
    if (columns_.size() >= LINE_CHARACTERS * CHARACTER_COLUMNS) {
      flushLine();
      port_.writeData(CHAR_LF);
    }
    const std::size_t glyph = static_cast<std::size_t>(value - FIRST_PRINTABLE) * GLYPH_ROWS;
    for (std::size_t column = 0; column < CHARACTER_COLUMNS; ++column) {
      std::uint8_t bits = 0;
      for (std::size_t row = 0; row < GLYPH_ROWS; ++row) {
        if (((FONT[glyph + row] >> column) & 1U) != 0) bits = static_cast<std::uint8_t>(bits | (0x80U >> row));
      }
      columns_.push_back(bits);
    }
    return;
  }
  switch (value) {
    case CHAR_CR:
      flushLine();
      break;
    case CHAR_LF:
      flushLine();
      port_.writeData(CHAR_LF);
      break;
    case CHAR_FF:
      flushLine();
      port_.writeData(CHAR_FF);
      break;
    default:
      break;
  }
}

void PrinterText::flushLine() {
  if (columns_.empty()) return;
  const std::size_t count = columns_.size();
  port_.writeData(CHAR_ESC);
  port_.writeData('*');
  port_.writeData(DENSITY_120_72);
  port_.writeData(static_cast<std::uint8_t>(count & 0xFFU));
  port_.writeData(static_cast<std::uint8_t>(count >> 8));
  for (const std::uint8_t column : columns_) port_.writeData(column);
  columns_.clear();
}

